#========================================
# Question 1: What are Escape Characters?
#========================================
# Escape characters are special character combinations
# that start with a backslash (\). They are used to
# perform special actions inside a string.


#==============================================
# Question 2: Why do we use Escape Characters?
#==============================================
# We use escape characters to:
# ✔ Print text on a new line.
# ✔ Add tab spaces.
# ✔ Print quotation marks inside a string.
# ✔ Print backslashes.
# ✔ Improve the formatting of output.


#=================================
#             Syntax
#=================================
# \n  -> New Line
# \t  -> Tab Space
# \"  -> Double Quote
# \'  -> Single Quote
# \\  -> Backslash
# Escape characters always start with a backslash (\).


#===========================================
# Task 1: Print Text on Two Separate Lines
#===========================================
print("Hello\nWelcome to Python")


#=====================================
# Task 2: Print Data Using Tab Space
#=====================================
print("Name\tClass\tMarks")


#=================================
# Task 3: Print Double Quotes
#=================================
print("My teacher said, \"Practice every day.\"")


#=============================
# Task 4: Print Single Quote
#=============================
print('It\'s a beautiful day.')


#======================================
# Task 5: Print a Windows File Path
#======================================
print("C:\\Program Files\\Python")


#================================================
# Task 6: Print Name and Age on Different Lines
#================================================
print("Name: Saba\nAge: 20")


#=======================================
# Task 7: Print a Simple Student Table
#=======================================
print("Name\tMarks")
print("Ali\t90")
print("Sara\t95")


#=======================================
# Task 8: Print Quotes Inside Quotes
#=======================================
print("Python is called \"Easy\" to learn.")


#==================================
# Task 9: Print a Folder Path
#==================================
print("D:\\Projects\\Python\\Day5")


#==========================================
# Task 10: Use Multiple Escape Characters
#==========================================
print("Name\tAge\nSaba\t20")


#================================================
#                    Summary
#================================================
# ✔ Escape characters start with a backslash (\).
# ✔ They are used to format strings.
# ✔ \n prints text on a new line.
# ✔ \t adds a tab space.
# ✔ \" prints double quotes.
# ✔ \' prints single quotes.
# ✔ \\ prints a backslash.
# ✔ Escape characters make the output cleaner and easier to read.
# ✔ Escape characters improve the readability of the output.


